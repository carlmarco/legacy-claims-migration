using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Etl.Core.IO;

public enum SqlDialect { Postgres, TSql }

/// <summary>Write migrated rows out as CSV, JSON, or a SQL INSERT script in Postgres or T-SQL dialect.</summary>
public static class OutputWriters
{
    public static string ToCsv(IReadOnlyList<string> columns, IEnumerable<object?[]> rows)
    {
        var sb = new StringBuilder(string.Join(",", columns.Select(Csv.Field))).Append('\n');
        foreach (var r in rows) sb.Append(string.Join(",", r.Select(Csv.Field))).Append('\n');
        return sb.ToString();
    }

    public static string ToJson(IReadOnlyList<string> columns, IEnumerable<object?[]> rows) =>
        JsonSerializer.Serialize(rows.Select(r => columns.Zip(r).ToDictionary(p => p.First, p => p.Second switch
        {
            DateOnly d => (object?)d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
            var x => x,
        })), new JsonSerializerOptions { WriteIndented = true });

    /// <summary>
    /// Multi-row INSERT statements. T-SQL caps a VALUES list at 1000 rows, so batches stay at 500 for both dialects.
    /// Identifiers are quoted per dialect ("x" vs [x]); strings are escaped (' -> ''); T-SQL uses N'' for Unicode.
    /// </summary>
    public static string ToSql(SqlDialect dialect, string schema, string table, IReadOnlyList<string> columns, IEnumerable<object?[]> rows)
    {
        string Id(string s) => dialect == SqlDialect.Postgres ? "\"" + s.Replace("\"", "\"\"") + "\"" : "[" + s.Replace("]", "]]") + "]";
        string Lit(object? v) => v switch
        {
            null => "NULL",
            bool b => dialect == SqlDialect.Postgres ? (b ? "TRUE" : "FALSE") : (b ? "1" : "0"),
            DateOnly d => dialect == SqlDialect.Postgres ? $"DATE '{d:yyyy-MM-dd}'" : $"CAST('{d:yyyy-MM-dd}' AS DATE)",
            string s => (dialect == SqlDialect.TSql ? "N'" : "'") + s.Replace("'", "''") + "'",
            IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
            _ => "'" + (v.ToString() ?? "").Replace("'", "''") + "'",
        };
        var sb = new StringBuilder($"-- {table}: generated by the etl engine ({dialect} dialect)\n");
        var head = $"INSERT INTO {Id(schema)}.{Id(table)} ({string.Join(", ", columns.Select(Id))}) VALUES\n";
        foreach (var chunk in rows.Chunk(500))
        {
            sb.Append(head);
            sb.Append(string.Join(",\n", chunk.Select(r => "  (" + string.Join(", ", r.Select(Lit)) + ")")));
            sb.Append(";\n");
        }
        return sb.ToString();
    }
}
